#!/usr/bin/env python3
"""Generate infra/user-data.sh from app/safeclick.py.

The app is embedded (gzip + base64) in the user data so every instance Auto
Scaling launches is self-contained: no git clone, no package installs, no
internet dependency at boot. Compressing keeps it under the 16 KB EC2 user
data limit. Run this after changing the app, then commit both files.
"""
import base64
import gzip
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app" / "safeclick.py"
OUT = ROOT / "infra" / "user-data.sh"
EC2_USER_DATA_LIMIT = 16 * 1024  # bytes, before base64 encoding

TEMPLATE = """#!/bin/bash
# SafeClick v0 bootstrap for Amazon Linux 2023.
# GENERATED by scripts/build_user_data.py. Edit app/safeclick.py instead.
set -euxo pipefail

mkdir -p /opt/safeclick
base64 -d <<'SAFECLICK_APP' | gunzip > /opt/safeclick/safeclick.py
{app}
SAFECLICK_APP

cat > /etc/systemd/system/safeclick.service <<'SAFECLICK_UNIT'
[Unit]
Description=SafeClick website safety checker
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=/usr/bin/python3 /opt/safeclick/safeclick.py
Environment=PORT=80
# Run as an unprivileged throwaway user that can still bind port 80
DynamicUser=yes
AmbientCapabilities=CAP_NET_BIND_SERVICE
NoNewPrivileges=yes
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
SAFECLICK_UNIT

systemctl daemon-reload
systemctl enable --now safeclick.service
"""


def main():
    packed = base64.b64encode(gzip.compress(APP.read_bytes(), mtime=0)).decode()
    app = "\n".join(textwrap.wrap(packed, 76))
    script = TEMPLATE.format(app=app)
    size = len(script.encode())
    if size > EC2_USER_DATA_LIMIT:
        raise SystemExit("user data is %d bytes, over the 16 KB EC2 limit" % size)
    OUT.write_text(script)
    print("wrote %s (%d bytes, limit %d)" % (OUT.relative_to(ROOT), size, EC2_USER_DATA_LIMIT))


if __name__ == "__main__":
    main()
